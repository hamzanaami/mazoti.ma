"""Write the showcase site's data files from the model.

    python scripts/build_site_data.py              # run the tests, then write site/data/
    python scripts/build_site_data.py --skip-tests # write without running the tests

Outputs (both derived, safe to commit):
    site/data/site_data.json  machine-readable copy
    site/data/site_data.js    same payload as a script, so the page also works from file://

A failing test blocks the build (docs/theory/03, section 2: failing checks block publication).
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
import tomllib
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from mazoti.site_data import build_payload  # noqa: E402

OUT_DIR = ROOT / "site" / "data"


def model_version() -> str:
    with open(ROOT / "pyproject.toml", "rb") as f:
        return tomllib.load(f)["project"]["version"]


def run_tests(today: str) -> dict:
    proc = subprocess.run(
        [sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider"],
        cwd=ROOT, capture_output=True, text=True,
    )
    summary = proc.stdout.strip().splitlines()[-1] if proc.stdout.strip() else ""
    counts = {k: int(n) for n, k in re.findall(r"(\d+) (passed|failed|error)", summary)}
    return {
        "passed": counts.get("passed", 0),
        "failed": counts.get("failed", 0) + counts.get("error", 0),
        "run_on": today,
        "command": "pytest -q",
        "ok": proc.returncode == 0,
        "summary": summary,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--skip-tests", action="store_true", help="do not run pytest first")
    args = parser.parse_args()

    today = date.today().isoformat()
    tests = None
    if not args.skip_tests:
        tests = run_tests(today)
        print(f"tests: {tests['summary']}")
        if not tests["ok"]:
            print("Tests failed: site data not written.", file=sys.stderr)
            return 1

    payload = build_payload(today, model_version(), tests)
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    text = json.dumps(payload, ensure_ascii=False, indent=1)
    (OUT_DIR / "site_data.json").write_text(text + "\n", encoding="utf-8")
    (OUT_DIR / "site_data.js").write_text(
        "// Generated by scripts/build_site_data.py. Do not edit by hand.\n"
        f"window.MAZOTI_DATA = {text};\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT_DIR / 'site_data.json'} and site_data.js")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
